package org.apache.iggy.kafka.demo;

/** JSON text helpers shared by the demo servers. */
final class DemoJson {

    private DemoJson() {}

    /** A JSON string: quotes and backslashes escaped, newlines as spaces, other control characters as \\uXXXX. */
    static String quote(String s) {
        StringBuilder out = new StringBuilder(s.length() + 2).append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '"' || c == '\\') {
                out.append('\\').append(c);
            } else if (c == '\n') {
                out.append(' ');
            } else if (c < 0x20) {
                out.append(String.format("\\u%04x", (int) c));
            } else {
                out.append(c);
            }
        }
        return out.append('"').toString();
    }
}
